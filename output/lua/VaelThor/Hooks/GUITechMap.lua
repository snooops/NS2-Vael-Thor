local kVTLineColor = Color(0.70, 0.45, 1.00, 0.5)
local kVTIconColors   -- copy of the vanilla marine colours with a violet "Available"

local function FindUpvalue(fn, wanted)
    if type(fn) ~= "function" then return nil end
    local i = 1
    while true do
        local name, value = debug.getupvalue(fn, i)
        if not name then return nil end
        if name == wanted then return value end
        i = i + 1
    end
end

local kTechMaps          = FindUpvalue(GUITechMap.Initialize, "kTechMaps")
local kLines             = FindUpvalue(GUITechMap.Initialize, "kLines")
local kStartOffset       = FindUpvalue(GUITechMap.Initialize, "kStartOffset")
local kLineColors        = FindUpvalue(FindUpvalue(GUITechMap.Initialize, "CreateLine"), "kLineColors")
local kTechMapIconColors = FindUpvalue(GUITechMap.Update, "kTechMapIconColors")

if not (kTechMaps and kLines and kStartOffset) then
    Shared.Message("[Vael'Thor] tech map: vanilla layout tables not found, J keeps the marine tree")
    return
end

local vanilla =
{
    map    = kTechMaps[kMarineTeamType],
    lines  = kLines[kMarineTeamType],
    offset = kStartOffset[kMarineTeamType],
    line   = kLineColors and kLineColors[kMarineTeamType],
    icons  = kTechMapIconColors and kTechMapIconColors[kMarineTeamType],
}

local kTechStatus = FindUpvalue(GUITechMap.Update, "kTechStatus")
if vanilla.icons and kTechStatus then
    kVTIconColors = {}
    for status, color in pairs(vanilla.icons) do
        kVTIconColors[status] = color
    end
    kVTIconColors[kTechStatus.Available] = Color(0.88, 0.78, 1.00, 1)
end

local applied
local function ApplyLayout(isVT)
    if applied == isVT then return end
    applied = isVT
    kTechMaps[kMarineTeamType]    = isVT and kVTTechMap or vanilla.map
    kLines[kMarineTeamType]       = isVT and kVTTechMapLines or vanilla.lines
    kStartOffset[kMarineTeamType] = isVT and kVTTechMapYStart or vanilla.offset
    if kLineColors then
        kLineColors[kMarineTeamType] = isVT and kVTLineColor or vanilla.line
    end
    if kTechMapIconColors and kVTIconColors then
        kTechMapIconColors[kMarineTeamType] = isVT and kVTIconColors or vanilla.icons
    end
end

local function LocalIsVT()
    return VT_GetLocalIsVT ~= nil and VT_GetLocalIsVT() == true
end

local oldInitialize = GUITechMap.Initialize
function GUITechMap:Initialize(...)
    self.vtLayout = LocalIsVT()
    ApplyLayout(self.vtLayout)
    return oldInitialize(self, ...)
end

-- Vanilla only rebuilds when the team TYPE changes; Vael'Thor <-> marine is the same type.
local oldUpdate = GUITechMap.Update
function GUITechMap:Update(...)
    if self.vtLayout ~= LocalIsVT() then
        self:Uninitialize()
        self:Initialize()
    end
    ApplyLayout(self.vtLayout)
    return oldUpdate(self, ...)
end

