-- Generates source/lua/VaelThor/Baseline/VanillaReference.lua: every scalar "k..." constant that the
-- vanilla balance files define, with its vanilla value (vt_isolation compares the game's values with it).
-- Usage: luajit extract_vanilla_balance.lua <NS2 install dir> <output file>
local ns2, out = arg[1], arg[2]

-- stub the engine: unknown globals are harmless callables/tables
local stub
stub = setmetatable({}, { __call = function() return stub end, __index = function() return stub end })
setmetatable(_G, { __index = function() return stub end })
Script = { Load = function(path) dofile(ns2 .. "/ns2/" .. path) end }
function PrecacheAsset(p) return p end
Shared = setmetatable({ GetThunderdomeEnabled = function() return false end }, { __index = function() return stub end })
function enum(t) local e = {} for i, v in ipairs(t) do e[v] = i; e[i] = v end return e end

local values, fileOf = {}, {}
local function run(file)
    local before = {}
    for k in pairs(_G) do before[k] = true end
    Script.Load(file)
    for k, v in pairs(_G) do
        local t = type(v)
        if type(k) == "string" and not before[k] and k:match("^k") and (t == "number" or t == "string" or t == "boolean")
                and values[k] == nil then
            values[k] = v; fileOf[k] = file
        end
    end
end
-- same as the game: Balance.lua loads BalanceHealth and BalanceMisc itself and then
-- overrides some of their values, so only the final state after Balance.lua counts
run("lua/Balance.lua")

local keys = {}
for k in pairs(values) do keys[#keys + 1] = k end
table.sort(keys)
local f = assert(io.open(out, "w"))
f:write("-- generated by art/tools/extract_vanilla_balance.lua from the NS2 install: vanilla balance constants\n")
f:write("VTVanillaReference =\n{\n")
for _, k in ipairs(keys) do
    local v = values[k]
    local s = type(v) == "string" and string.format("%q", v) or tostring(v)
    if type(v) == "number" and (v ~= v or v == math.huge or v == -math.huge) then s = "nil" end
    f:write(string.format("    %s = %s,\n", k, s))
end
f:write("}\n")
f:close()
print(#keys .. " constants -> " .. out)
