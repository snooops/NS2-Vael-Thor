#!/usr/bin/env bash
# Builds every Vael'Thor building model from the original procedural Blender designs
# (art/buildings/concepts/make_concepts.py, exported by export_concepts.py into art/buildings/procedural/).
# The old Tripo GLBs in art/buildings/glb/ are no longer used. Usage: build_all.sh [model names...]  (default: all)
#   name      glb                   height  tris   collision: auto:<slice m>[:<clear centre radius m>] = model-following
#                                                  hulls (prepare_building.py auto_hulls); legacy "a-b,c-d" height bands
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
BUILDINGS=(
  "nexus     nexus                 4.2  15000  auto:0.35"
  "chamber   synthesis_chamber     2.6  12000  auto:0.3"
  "spire     psionic_spire         5.0  12000  auto:0.4"
  "pylon     pylon                 3.2  10000  auto:0.35"
  "siphon    siphon                3.2  12000  auto:0.35"
  "shieldgen shield_generator      2.4  12000  auto:0.3"
  "obelisk   sentinel_obelisk      3.8  10000  auto:0.35"
  "rift      rift_portal           3.0  12000  auto:0.3:0.6:0.95@1.72"  # walk-in column + portal membrane kept free, ring solid
)
blender -b --factory-startup --python-exit-code 1 -P "$HERE/concepts/export_concepts.py" -- "$HERE/procedural" 2>&1 \
  | grep -E "EXPORTED|Error|Traceback" | grep -v OpenColorIO || true
for line in "${BUILDINGS[@]}"; do
  read -r name glb height tris bands <<<"$line"
  if [ $# -gt 0 ] && [[ ! " $* " =~ " $name " ]]; then continue; fi
  echo "########## $name"
  "$HERE/build_building.sh" "$name" "$HERE/procedural/$glb.glb" "$height" "$tris" "$bands"
done

# Part pivots of every building with moving parts -> Lua table for VTBuildingAnim.lua (source + output copy)
python3 -I - "$HERE/../.." <<'PY'
import sys, os, json, glob
mod = sys.argv[1]
lines = ["-- GENERATED by art/buildings/build_all.sh - do not edit. Pivots of the animated building parts",
         "-- (models/vaelthor/<name>/<name>_<group>.model) in model coordinates before kVTStructureModelScale.",
         "kVTBuildingPartPivots =", "{"]
for f in sorted(glob.glob(os.path.join(mod, "source/modelsrc/vaelthor/*/*_parts.json"))):
    name = os.path.basename(f)[:-len("_parts.json")]
    groups = ", ".join("%s = Vector(%.4f, %.4f, %.4f)" % (g, *p) for g, p in sorted(json.load(open(f)).items()))
    lines.append("    %s = { %s }," % (name, groups))
lines.append("}")
for out in ("source/lua/VaelThor/VTBuildingParts.lua", "output/lua/VaelThor/VTBuildingParts.lua"):
    open(os.path.join(mod, out), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
PY
